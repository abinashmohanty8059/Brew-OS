import type { PreparedDrink } from "@/types";

/** Builds a drink definition and derives its total preparation time from its steps. */
export function defineDrink(drink: Omit<PreparedDrink, "kind" | "prepSeconds" | "listed"> & { listed?: boolean }): PreparedDrink {
  return {
    ...drink,
    kind: "prepared_drink",
    listed: drink.listed ?? true,
    prepSeconds: Math.round(drink.steps.reduce((sum, s) => sum + s.seconds, 0) * 10) / 10,
  };
}

